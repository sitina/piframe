#!/usr/bin/env python3
"""Derive the Bookworm ARMv6 artifact lock from the universal version lock.

Run with development dependencies installed. piwheels is an explicitly trusted
binary builder for this profile; review changes to URLs, hashes and apt packages.
"""
import json
from pathlib import Path
from urllib.request import urlopen

from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
NATIVE = {'cffi', 'contourpy', 'cryptography', 'kiwisolver', 'markupsafe',
          'matplotlib', 'numpy', 'pillow', 'protobuf'}
PURE = {'charset-normalizer', 'fonttools'}


def generate(fetch):
    env = default_environment()
    env.update(python_version='3.11', python_full_version='3.11.2',
               platform_machine='armv6l', sys_platform='linux', platform_system='Linux',
               platform_python_implementation='CPython', implementation_name='cpython')
    output = ['# Generated by scripts/lock_pi.py; Bookworm CPython 3.11 ARMv6 only.',
              '# Native artifacts: piwheels; other artifacts: hashed PyPI wheels.',
              '--index-url https://pypi.org/simple', '--only-binary :all:']
    apt = {'python3.11-venv', 'libffi8', 'libstdc++6', 'zlib1g'}
    artifacts = {}
    for line in (ROOT / 'requirements.txt').read_text().replace('\\\n', '').splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        requirement = Requirement(line.split('--hash')[0].strip())
        if requirement.marker and not requirement.marker.evaluate(env):
            continue
        name = requirement.name
        version = next(iter(requirement.specifier)).version
        if name in NATIVE | PURE:
            release = fetch(name)['releases'][version]
            candidates = [(filename, info) for filename, info in release['files'].items()
                          if (name in NATIVE and
                              (f'-cp311-cp311-linux_armv6l.whl' in filename or
                               f'-cp311-abi3-linux_armv6l.whl' in filename)) or
                          (name in PURE and filename.endswith('-none-any.whl'))]
            if len(candidates) != 1:
                raise ValueError(f'Expected one target artifact for {name}=={version}')
            filename, info = candidates[0]
            url = info['file_url']
            if url.startswith('/'):
                url = 'https://www.piwheels.org' + url
            if not url.startswith('https://www.piwheels.org/simple/'):
                raise ValueError('Unexpected artifact origin')
            digest = info['filehash']
            if len(digest) != 64 or any(c not in '0123456789abcdef' for c in digest):
                raise ValueError('Invalid SHA256')
            output.append(f'{name} @ {url} --hash=sha256:{digest}')
            apt.update(info['apt_dependencies'])
            artifacts[name] = {'version': version, 'url': url, 'sha256': digest,
                               'apt_dependencies': info['apt_dependencies']}
        else:
            # Preserve the reviewed PyPI hashes, removing now-evaluated markers.
            output.append(f'{name}=={version} ' + '--hash' + line.split('--hash', 1)[1])
    return '\n'.join(output) + '\n', sorted(apt), artifacts


def main():
    def fetch(name):
        with urlopen(f'https://www.piwheels.org/project/{name}/json/', timeout=60) as response:
            return json.load(response)
    lock, apt, artifacts = generate(fetch)
    (ROOT / 'requirements-pi-bookworm.txt').write_text(lock)
    (ROOT / 'deployment/pi-bookworm-artifacts.json').write_text(
        json.dumps({'apt_packages': apt, 'artifacts': artifacts}, indent=2) + '\n')


if __name__ == '__main__':
    main()
